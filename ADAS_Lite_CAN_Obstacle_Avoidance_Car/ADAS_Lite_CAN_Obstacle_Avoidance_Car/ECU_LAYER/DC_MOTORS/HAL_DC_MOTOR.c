#include "HAL_DC_MOTOR.h"
pin_config_t DC_MOTOR_1_PIN = {
		.port = PORTC_INDEX,
		.pin = GPIO_PIN0,
		.direction = GPIO_DIRECTION_OUTPUT,
		.logic = GPIO_LOW
};
pin_config_t DC_MOTOR_2_PIN = {
		.port = PORTC_INDEX,
		.pin = GPIO_PIN1,
		.direction = GPIO_DIRECTION_OUTPUT,
		.logic = GPIO_LOW
};
pin_config_t DC_MOTOR_3_PIN = {
		.port = PORTD_INDEX,
		.pin = GPIO_PIN3,
		.direction = GPIO_DIRECTION_OUTPUT,
		.logic = GPIO_LOW
};
pin_config_t DC_MOTOR_4_PIN = {
		.port = PORTD_INDEX,
		.pin = GPIO_PIN2,
		.direction = GPIO_DIRECTION_OUTPUT,
		.logic = GPIO_LOW
};

void DC_MOTOR_INIT(void){
	GPIO_PIN_INIT(&DC_MOTOR_1_PIN);
	GPIO_PIN_INIT(&DC_MOTOR_2_PIN);
	GPIO_PIN_INIT(&DC_MOTOR_3_PIN);
	GPIO_PIN_INIT(&DC_MOTOR_4_PIN);
}
void DC_MOTOR_MOVE_FORWARD(void){
	GPIO_PIN_WRITE_LOGIC(&DC_MOTOR_1_PIN, GPIO_HIGH);
	GPIO_PIN_WRITE_LOGIC(&DC_MOTOR_2_PIN, GPIO_LOW);
	GPIO_PIN_WRITE_LOGIC(&DC_MOTOR_3_PIN, GPIO_HIGH);
	GPIO_PIN_WRITE_LOGIC(&DC_MOTOR_4_PIN, GPIO_LOW);
}
void DC_MOTOR_MOVE_BACKWARD(void){
	GPIO_PIN_WRITE_LOGIC(&DC_MOTOR_1_PIN, GPIO_LOW);
	GPIO_PIN_WRITE_LOGIC(&DC_MOTOR_2_PIN, GPIO_HIGH);
	GPIO_PIN_WRITE_LOGIC(&DC_MOTOR_3_PIN, GPIO_LOW);
	GPIO_PIN_WRITE_LOGIC(&DC_MOTOR_4_PIN, GPIO_HIGH);
}
void DC_MOTOR_MOVE_RIGHT(void){
	GPIO_PIN_WRITE_LOGIC(&DC_MOTOR_1_PIN, GPIO_HIGH);
	GPIO_PIN_WRITE_LOGIC(&DC_MOTOR_2_PIN, GPIO_LOW);
	GPIO_PIN_WRITE_LOGIC(&DC_MOTOR_3_PIN, GPIO_LOW);
	GPIO_PIN_WRITE_LOGIC(&DC_MOTOR_4_PIN, GPIO_LOW);
}
void DC_MOTOR_MOVE_LEFT(void){
	GPIO_PIN_WRITE_LOGIC(&DC_MOTOR_1_PIN, GPIO_LOW);
	GPIO_PIN_WRITE_LOGIC(&DC_MOTOR_2_PIN, GPIO_LOW);
	GPIO_PIN_WRITE_LOGIC(&DC_MOTOR_3_PIN, GPIO_HIGH);
	GPIO_PIN_WRITE_LOGIC(&DC_MOTOR_4_PIN, GPIO_LOW);
}
void DC_MOTOR_STOP(void){
	GPIO_PIN_WRITE_LOGIC(&DC_MOTOR_1_PIN, GPIO_LOW);
	GPIO_PIN_WRITE_LOGIC(&DC_MOTOR_2_PIN, GPIO_LOW);
	GPIO_PIN_WRITE_LOGIC(&DC_MOTOR_3_PIN, GPIO_LOW);
	GPIO_PIN_WRITE_LOGIC(&DC_MOTOR_4_PIN, GPIO_LOW);
}
